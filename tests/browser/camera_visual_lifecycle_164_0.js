async (page) => {
    // Start the harness with a fresh --db and --test-controls. Time remains 1800 s;
    // only the explicit fixture clock is advanced, never the production duration.
    const checks=[];const check=(ok,name)=>{if(!ok)throw Error(name);checks.push(name);};
    const preview=()=>page.locator('[data-kind=preview]');
    const state=()=>page.evaluate(()=>fetch('/api/state').then(r=>r.json()));
    const minimizePreview=async()=>{if(await preview().isVisible())await preview().locator('.workspace-minimize-btn').click();};
    await page.context().clearCookies();
    await page.setViewportSize({width:1440,height:1000});
    await page.goto('http://127.0.0.1:8999');
    await page.locator('#login').click();
    await page.waitForFunction(()=>document.querySelector('#session').textContent==='cvn-alice');
    await page.locator('#open').click();
    const original=await page.locator('[data-kind=reference]').getAttribute('data-app-id');
    check(await preview().count()===0,'No preview before successful operation');
    await page.locator('[data-action=connect]').click();
    await page.getByText('SESSION CLOSE',{exact:false}).waitFor();
    const initial=await state();
    check(initial.operations.length===0,'No download before SESSION CLOSE deadline');
    await page.screenshot({path:'artifacts/cvn-164-0-b-session-close.png',fullPage:true});
    await page.reload();
    await page.locator('[data-kind=operations]').waitFor({timeout:10000});
    check(await page.locator('[data-kind=reference]').count()===0,'Reference instance closes automatically across reload');
    let s=await state();
    check(s.receipt.close_at===initial.receipt.close_at,'Reload does not extend SESSION CLOSE');
    check(s.receipt.end_at-s.receipt.start_at===1800,'Download duration is exactly 30 minutes');
    check(s.operations.length===1&&s.files.length===0,'One operation, no activation file early');
    await page.locator('#advance').click();
    await page.waitForFunction(()=>document.querySelector('.download-percent')?.textContent==='50%');
    await page.screenshot({path:'artifacts/cvn-164-0-b-download.png',fullPage:true});
    const mid=await state();
    await page.locator('[data-kind=operations] .close-btn').click();
    await page.reload();
    await page.locator('.download-percent').waitFor();
    check((await state()).receipt.end_at===mid.receipt.end_at,'Closing Operations and refreshing preserves download deadline');
    await page.locator('#logout').click();
    await page.locator('#login').click();
    await page.locator('.download-percent').waitFor();
    check((await state()).receipt.id===mid.receipt.id,'Re-login restores same activation receipt');
    await page.locator('#advance').click();
    await preview().locator('img').waitFor({timeout:10000});
    await preview().locator('img').evaluate(i=>i.decode());
    const id=await preview().getAttribute('data-app-id');
    s=await state();
    check(s.receipt.file_verified&&s.receipt.progress===100,'Preview requires 100% and verified committed file');
    check(s.files.length===1&&s.operations.length===1,'Exactly one disk artifact and operation');
    check(id!==original&&id===s.receipt.instance_id,'Viewer is a separate standard application instance');
    check(await preview().getAttribute('data-app-interface')==='window','Viewer uses standard window interface');
    await page.screenshot({path:'artifacts/cvn-164-0-b-desktop.png',fullPage:true});
    // Standard window controls and actual drag handler extracted from terminal.js.
    await preview().locator('.browser-maximize-btn').click();
    check(await preview().evaluate(e=>e.classList.contains('is-window-maximized')),'Standard maximize');
    await preview().locator('.browser-maximize-btn').click();
    const before=await preview().boundingBox();
    const title=await preview().locator('.window-name').boundingBox();
    await page.mouse.move(title.x+80,title.y+20);await page.mouse.down();await page.mouse.move(title.x+120,title.y+45);await page.mouse.up();
    const after=await preview().boundingBox();
    check(Math.abs(after.x-before.x)>10,'Standard drag changes window position');
    await minimizePreview();
    check(await preview().evaluate(e=>e.classList.contains('is-window-minimized')),'Standard minimize');
    await page.locator('#tasks button').filter({hasText:/^GLASS EYE$/}).click();
    check(await preview().isVisible(),'Taskbar restores same instance');
    await preview().locator('[data-info]').click();
    await preview().locator('[data-external]').click();
    await page.keyboard.press('Escape');
    check(await preview().locator('[data-external]').evaluate(e=>e===document.activeElement),'Source dialog restores focus');
    await preview().locator('[data-hide]').click();
    // Second tab shares login but cannot claim an already leased viewer.
    const other=await page.context().newPage();
    await other.goto('http://127.0.0.1:8999');
    await other.locator('[data-kind=operations]').waitFor();
    await other.waitForTimeout(1300);
    check(await other.locator('[data-kind=preview]').count()===0,'Second tab cannot duplicate leased instance');
    await other.close();
    await page.bringToFront();
    await preview().locator('.close-btn').click();
    await page.waitForFunction(async()=>{const s=await fetch('/api/state').then(r=>r.json());return s.receipt.closed;});
    await page.reload();
    await page.locator('[data-kind=operations]').waitFor();
    check(await preview().count()===0,'Explicit viewer close persists across refresh');
    await page.locator('#open').click();
    await preview().locator('img').waitFor();
    check(await preview().getAttribute('data-app-id')===id,'Explicit reopen reuses the durable viewer instance');
    await minimizePreview();
    await page.locator('#language').selectOption('EN');
    await page.emulateMedia({reducedMotion:'reduce'});
    await page.locator('#tasks button').filter({hasText:/^GLASS EYE$/}).click();
    await page.setViewportSize({width:390,height:844});
    await preview().locator('img').waitFor();
    check(await preview().locator('img').evaluate(e=>getComputedStyle(e).animationName)==='none','Reduced motion in standard viewer');
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile has no horizontal overflow');
    await page.screenshot({path:'artifacts/cvn-164-0-b-mobile.png',fullPage:true});
    await minimizePreview();
    await page.setViewportSize({width:1440,height:1000});
    await page.locator('#logout').click();
    await page.locator('#account').selectOption('cvn-bob');
    await page.locator('#login').click();
    await page.waitForFunction(()=>document.querySelector('#session').textContent==='cvn-bob');
    await page.locator('#outcome').selectOption('failure');
    await page.locator('#open').click();
    await page.locator('[data-action=connect]').click();
    await page.locator('.choice-result').filter({hasText:'FAILURE'}).waitFor();
    await page.locator('#advance').click();
    await page.reload();
    await page.locator('.choice-result').filter({hasText:'FAILURE'}).waitFor();
    s=await state();
    check(s.receipt.state==='FAILED'&&s.operations.length===0&&s.files.length===0,'Failure persists without download or file');
    check(await preview().count()===0&&await page.locator('[role=timer]').count()===0,'Failure leaves reference terminal without auto-close or preview');
    await page.screenshot({path:'artifacts/cvn-164-0-b-failure.png',fullPage:true});
    return {passed:checks.length,checks};
}
