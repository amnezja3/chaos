async(page)=>{
    const assert=(v,m)=>{if(!v)throw Error(m);};
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    let requests=0;
    const snapshot={cycle:{cycle_id:'test-cycle',status:'active'},state_version:1,summary:{parts_discovered:1,parts_active:0,parts_blocked:1,parts_public:0},parts:[{public_entity_id:'opaque-1',display_label:'Author <part>',visibility_level:'full_owner',summary:'PEŁNE DANE KOMPONENTU',identity_visible:true,part_code:'P1',status:'blocked',viewer_relation:'self_foreign_blocked',location:{visibility:'exact'},actions:{can_show_on_map:true,can_teleport:true,map_target_type:'ghostnetwork_part',map_target_id:'opaque-1',teleport_target_type:'ghostnetwork_part',teleport_target_id:'opaque-1'}}],groups:{self_foreign:['opaque-1']},connections:[]};
    const fulfill=async(route,json)=>{const res=await page.request.get('http://127.0.0.1:8993/api/profile');await route.fulfill({headers:res.headers(),json});};
    await page.route('**/api/ghostnetwork/snapshot?view=suite',async route=>{requests++;await fulfill(route,snapshot);});
    await page.route('**/api/ghostnetwork/archive/signals?*',route=>fulfill(route,{ok:true,signals:[]}));
    await page.route('**/api/ghostnetwork/rankings**',route=>fulfill(route,{ok:true,rankings:[],players:[],clans:[]}));
    await page.goto('http://127.0.0.1:8993').catch(()=>{});
    await page.evaluate(()=>{sessionStorage.clear();localStorage.clear();});
    await page.goto('http://127.0.0.1:8993');
    await page.evaluate(()=>createGhostNetworkSuiteApp());
    const app=page.locator('[data-app=ghostnetwork-suite]');
    await app.locator('[data-part-ref=opaque-1]').waitFor();
    await app.locator('[data-suite-search]').fill('Author');
    await app.locator('details summary').click();
    const before=requests;
    await page.evaluate(()=>GhostLocale.changeLocale('en',false));
    assert(await app.locator('[data-suite-search]').inputValue()==='Author','search preserved');
    assert(await app.locator('details').getAttribute('open')!==null,'expanded detail preserved');
    assert((await app.innerText()).includes('FULL COMPONENT DATA'),'system summary translated');
    assert((await app.innerText()).includes('Author <part>'),'visible name preserved');
    assert(requests===before,'locale does not refetch');
    await app.locator('[data-suite-card-action=teleport]').click();
    await page.evaluate(()=>GhostLocale.changeLocale('pl',false));
    assert((await page.locator('[role=dialog]').innerText()).includes('Wykonać teleport'),'teleport dialog follows locale');
    await page.locator('[data-choice=cancel]').click();
    await app.locator('.close-btn').click();
    await page.evaluate(()=>createGhostSignalArchiveApp());
    const archive=page.locator('[data-app=ghostsignal-archive]');
    await archive.locator('[data-ghostsignal-refresh]').waitFor();
    await page.evaluate(()=>GhostLocale.changeLocale('en',false));
    assert((await archive.innerText()).includes('No archived signals.'),'registry empty translated');
    assert((await archive.innerText()).includes('PLAYERS // ALL-TIME'),'rank headings translated');
    await page.setViewportSize({width:390,height:844});
    assert(await archive.locator('[data-ghostsignal-refresh]').isVisible(),'mobile refresh');
    assert(!errors.length,JSON.stringify(errors));
    return {pass:true,requests,errors};
}
