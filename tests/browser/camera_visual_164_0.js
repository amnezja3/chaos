async (page) => {
    const checks=[];
    const check=(ok,name)=>{if(!ok)throw new Error(name);checks.push(name);};
    await page.setViewportSize({width:1440,height:1000});
    await page.goto('http://127.0.0.1:8999/');
    await page.locator('#open').click();
    check(await page.locator('.viewport img').count()===0,'No image before simulated operation approval');
    await page.locator('[data-action=connect]').click();
    await page.getByText('ARCHIVE LINK',{exact:true}).waitFor();
    await page.locator('.viewport img').evaluate(i=>i.decode());
    check(await page.locator('.viewport img').evaluate(i=>i.naturalWidth===960),'Local thumbnail decoded');
    await page.locator('#open').click();
    await page.locator('#application').selectOption('legacy');
    await page.locator('#open').click();
    check(await page.locator('.app-window').count()===1,'Repeated/new/legacy launcher reuses one window (fixture binding)');
    await page.locator('[data-frame=detail]').click();
    check(await page.locator('.viewport').getAttribute('data-frame')==='detail','Explicit crop of same image');
    await page.locator('[data-frame=full]').click();
    await page.locator('[data-pause]').click();
    check(await page.locator('.app-window').evaluate(e=>e.classList.contains('cvn-paused')),'Pause stops animation');
    await page.locator('[data-info]').click();
    check((await page.locator('.cvn-panel').innerText()).includes('Cybularny'),'Visible provenance');
    await page.locator('[data-copy]').click();
    check((await page.locator('#copy-status').innerText()).length>0,'Clipboard success or manual-copy fallback');
    await page.locator('[data-external]').click();
    check(await page.locator('dialog').isVisible(),'External connection confirmation');
    await page.keyboard.press('Escape');
    check(await page.locator('dialog').count()===0,'Escape closes confirmation');
    check(await page.locator('[data-external]').evaluate(e=>e===document.activeElement),'Escape restores focus');
    await page.locator('.close-btn').click();
    check(await page.locator('.app-window').count()===0,'Close removes window');
    await page.locator('#open').click();
    await page.getByText('ARCHIVE LINK',{exact:true}).waitFor();
    check(await page.locator('[data-action=connect]').count()===0,'Reopen reuses accepted fixture operation');
    for(const [value,label] of [['NO_COVERAGE','NO SIGNAL'],['FAILED','SIGNAL LOST'],['REVOKED','REVOKED']]){
        await page.locator('#scenario').selectOption(value);
        await page.locator('.empty strong').filter({hasText:label}).waitFor();
        check(await page.locator('.viewport img').count()===0,value+' has no stale photo');
    }
    await page.locator('#language').selectOption('EN');
    await page.locator('#scenario').selectOption('READY');
    await page.emulateMedia({reducedMotion:'reduce'});
    await page.getByText('ARCHIVE LINK',{exact:true}).waitFor();
    check(await page.locator('.viewport img').evaluate(i=>getComputedStyle(i).animationName)==='none','Reduced motion');
    check(await page.locator('.archive').innerText()==='Archive material — simulation, not a live feed','English archive label');
    await page.setViewportSize({width:390,height:844});
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile has no horizontal overflow');
    await page.screenshot({path:'artifacts/cvn-164-0-mobile-en.png',fullPage:true});
    await page.locator('[data-info]').click();
    await page.locator('[data-external]').click();
    await page.screenshot({path:'artifacts/cvn-164-0-external-en.png',fullPage:true});
    const target=await page.locator('dialog a').getAttribute('href');
    await page.route(target,route=>route.fulfill({status:200,contentType:'text/html',body:'<title>External navigation test destination</title>'}));
    await page.locator('dialog a').click();
    await page.waitForURL(target);
    check(page.url()===target,'Confirmed same-tab navigation (destination intercepted locally)');
    await page.unroute(target);
    await page.goto('http://127.0.0.1:8999/');
    await page.locator('#open').click();
    await page.locator('[data-action=connect]').click();
    await page.getByText('ARCHIVE LINK',{exact:true}).waitFor();
    await page.locator('.viewport img').evaluate(i=>i.decode());
    await page.screenshot({path:'artifacts/cvn-164-0-mobile-pl.png',fullPage:true});
    await page.locator('#scenario').selectOption('NO_COVERAGE');
    await page.locator('.empty strong').filter({hasText:'NO SIGNAL'}).waitFor();
    await page.screenshot({path:'artifacts/cvn-164-0-no-signal.png',fullPage:true});
    // Close during synchronization: no timer can recreate a removed window.
    await page.emulateMedia({reducedMotion:'no-preference'});
    await page.locator('#scenario').selectOption('READY');
    await page.locator('.close-btn').click();
    await page.waitForTimeout(1100);
    check(await page.locator('.app-window').count()===0,'Close during synchronization does not resurrect window');
    await page.route('**/walowa.jpg',r=>r.fulfill({status:200,contentType:'image/jpeg',body:'invalid image fixture'}));
    await page.locator('#open').click();
    await page.locator('.empty strong').filter({hasText:'ARCHIVE CORRUPTED'}).waitFor();
    check(await page.locator('.viewport img').count()===0,'Decode failure removes image without retry');
    await page.unroute('**/walowa.jpg');
    return {passed:checks.length,checks};
}
