"""UI smoke test. Requires a fresh tools/identity_gateway_browser_fixture.py on 8997.
Install Playwright separately in the local test environment, not production.
Mocks only external OAuth page, launch handoff and unrelated gameplay queues.
Account, reauthentication and SMTP settings use the real fixture endpoints.
"""
from playwright.sync_api import sync_playwright, expect
with sync_playwright() as p:
 b=p.chromium.launch()
 context=b.new_context(viewport={'width':1440,'height':1000})
 page=context.new_page();errors=[]
 page.route('http://127.0.0.1:8997/launch',lambda route:route.fulfill(status=302,headers={'Location':'/__fixture/workspace'}))
 headers=lambda route:{'X-Chaos-Session-Generation':route.request.headers.get('x-chaos-session-generation',''),'X-Chaos-Session-User':'alice'}
 page.route('**/launch-queue',lambda route:route.fulfill(json=[],headers=headers(route)))
 page.route('**/api/state/changes?*',lambda route:route.fulfill(json={'ok':True,'changes':[],'current_version':0},headers=headers(route)))
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto('http://127.0.0.1:8997/__fixture/account/alice?locale=en')
 page.goto('http://127.0.0.1:8997/launch')
 page.wait_for_function('typeof createSettings === "function" && typeof createIdentitySettingsWindow === "function"')
 page.locator('#boot-preloader').wait_for(state='hidden',timeout=60000)
 page.evaluate('createSettings()')
 page.locator('[data-settings-identity]').click()
 frame=page.frame_locator('[data-app="identity-settings"] iframe')
 expect(frame.locator('.identity-method')).to_have_count(4)
 assert len(context.pages)==1
 frame.locator('#reauth-password').fill('wrong')
 frame.locator('.identity-method--google button').click()
 expect(frame.locator('.identity-method--google [data-operation-status]')).to_contain_text('Identity confirmation failed')
 expect(page.locator('.system-toast.error')).to_be_visible()
 print('PASS desktop: internal window, one tab, inline error + system toast')
 frame.locator('#reauth-password').fill('Secret123')
 page.route('https://accounts.google.com/**',lambda route:route.fulfill(content_type='text/html',body='<h1>Mock OAuth provider</h1>'))
 frame.locator('.identity-method--google button').click()
 page.wait_for_url('https://accounts.google.com/**')
 assert len(context.pages)==1
 print('PASS provider navigation: top-level same tab')
 page.goto('http://127.0.0.1:8997/account/identity')
 page.wait_for_url('**/__fixture/workspace')
 expect(page.frame_locator('[data-app="identity-settings"] iframe').locator('.identity-method')).to_have_count(4)
 print('PASS return: internal account window reopens')
 page.locator('#boot-preloader').wait_for(state='hidden',timeout=60000)
 page.screenshot(path='.playwright-mcp/identity-157-ux-workspace.png')
 frame=page.frame_locator('[data-app="identity-settings"] iframe')
 frame.locator('[data-identity-return]').first.click()
 expect(page.locator('[data-app="identity-settings"]')).to_have_count(0)
 page.set_viewport_size({'width':390,'height':844})
 page.evaluate('createIdentitySettingsWindow()')
 frame=page.frame_locator('[data-app="identity-settings"] iframe')
 expect(frame.locator('.identity-method')).to_have_count(4)
 assert frame.locator('body').evaluate('(e)=>document.documentElement.scrollWidth<=innerWidth+1')
 page.screenshot(path='.playwright-mcp/identity-157-ux-mobile.png')
 print('PASS mobile: internal window, no content overflow')
 page.goto('http://127.0.0.1:8997/__fixture/account/admin?locale=en')
 expect(page.locator('#smtp-secret-state')).to_contain_text('missing')
 page.locator('#identity-mail button').click()
 expect(page.locator('#identity-mail [data-operation-status]')).not_to_be_empty()
 page.locator('#reauth-password').fill('Secret123')
 page.locator('#identity-mail select[name=mode]').select_option('disabled')
 page.locator('#identity-mail input[name=host]').fill('smtp.example.test')
 page.locator('#identity-mail input[name=sender]').fill('sender@example.test')
 page.locator('#identity-mail input[name=password]').fill('fixture-secret')
 page.locator('#identity-mail button').click()
 expect(page.locator('#smtp-secret-state')).to_contain_text('configured')
 expect(page.locator('#identity-mail [data-operation-status]')).to_contain_text('Changes saved')
 expect(page.locator('#identity-mail input[name=password]')).to_have_value('')
 page.locator('#identity-mail-test input').fill('test@example.test')
 page.locator('#identity-mail-test button').click()
 expect(page.locator('#identity-mail-test [data-operation-status]')).to_contain_text('Mail is not configured')
 print('PASS admin: save feedback and test error beside respective buttons')
 page.screenshot(path='.playwright-mcp/identity-157-ux-admin-mobile.png')
 page.goto('http://127.0.0.1:8997/__fixture/account/alice?locale=pl')
 expect(page.locator('main h1')).to_have_text('Konto i bezpieczeństwo')
 page.locator('#reauth-password').fill('wrong')
 page.locator('.identity-method--google button').click()
 expect(page.locator('.identity-method--google [data-operation-status]')).to_contain_text('Nieprawidłowe')
 print('PASS PL: localized account and inline failure')
 anonymous=context.browser.new_context()
 entry=anonymous.new_page()
 entry.goto('http://127.0.0.1:8997/?login=1')
 button=entry.locator('[data-identity-provider=google]')
 assert button.evaluate('(e)=>getComputedStyle(e).cursor')=='pointer'
 button.evaluate('(e)=>e.disabled=true')
 assert button.evaluate('(e)=>getComputedStyle(e).cursor')=='not-allowed'
 anonymous.close()
 print('PASS entry: enabled/disabled cursors')
 print('PAGE_ERRORS',errors)
 assert not errors
 b.close()
